import 'package:flutter/material.dart';

/// A colored circular icon chip — the "each settings row gets its own
/// tinted icon" look used throughout Profile. One small widget instead of
/// repeating the same Container/BoxDecoration everywhere it's needed.
class IconBadge extends StatelessWidget {
  final IconData icon;
  final Color color;
  final double size;

  const IconBadge({super.key, required this.icon, required this.color, this.size = 40});

  @override
  Widget build(BuildContext context) {
    return Container(
      width: size,
      height: size,
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.12),
        borderRadius: BorderRadius.circular(size * 0.3),
      ),
      child: Icon(icon, color: color, size: size * 0.52),
    );
  }
}
